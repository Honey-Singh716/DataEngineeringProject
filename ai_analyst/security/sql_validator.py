"""
ai_analyst/security/sql_validator.py
Multi-layer SQL validation using sqlglot AST analysis.

validate_sql(sql: str) → ValidationResult

Validation layers:
  1. Parse with sqlglot (PostgreSQL dialect) – syntax check
  2. Exactly one statement
  3. Only SELECT (and CTE SELECT) at top level – no DDL/DML
  4. No disallowed statement types (UPDATE, INSERT, DELETE, DROP, ALTER, …)
  5. Table allowlist: every referenced table must be in ALLOWED_TABLES
     under ALLOWED_SCHEMA; staging tables always rejected
  6. Forbidden schema access (pg_catalog, information_schema, public)
  7. No dangerous function calls (pg_read_file, pg_ls_dir, dblink, …)
  8. CTE check: no data-modifying CTEs (INSERT/UPDATE/DELETE inside WITH)
  9. Subquery check: same rules applied recursively
 10. LIMIT enforcement: if no LIMIT present, inject LIMIT {max_rows}
"""
from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from typing import Optional

import sqlglot
import sqlglot.expressions as exp

from ai_analyst.config import settings
from ai_analyst.security.table_allowlist import (
    ALLOWED_SCHEMA,
    ALLOWED_TABLES,
    FORBIDDEN_SCHEMAS,
    FORBIDDEN_TABLE_PATTERNS,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Dangerous functions that must never appear in generated queries
# ---------------------------------------------------------------------------

_DANGEROUS_FUNCTIONS: frozenset[str] = frozenset(
    {
        # File-system / OS access
        "pg_read_file", "pg_ls_dir", "pg_read_binary_file",
        "pg_stat_file",
        # Network / remote
        "dblink", "dblink_exec", "dblink_connect",
        "http_get", "http_post",
        # Code execution
        "pg_execute_server_program",
        # Privilege escalation
        "set_config",
        # Other dangerous built-ins
        "pg_sleep",   # DoS via long sleeps
        "lo_import", "lo_export",
        "pg_cancel_backend", "pg_terminate_backend",
    }
)

# Disallowed SQL node types (DML / DDL / utility)
_DISALLOWED_NODE_TYPES: tuple[type, ...] = (
    exp.Insert,
    exp.Update,
    exp.Delete,
    exp.Drop,
    exp.Create,
    exp.Alter,
    exp.Command,        # catches COPY, VACUUM, etc.
    exp.Transaction,
    exp.Commit,
    exp.Rollback,
    exp.Set,            # SET <variable>
    exp.Use,
    exp.Grant,
    exp.Revoke,
    exp.Merge,
    exp.LoadData,
)


# ---------------------------------------------------------------------------
# Result container
# ---------------------------------------------------------------------------

@dataclass
class ValidationResult:
    """Outcome of a validate_sql() call."""
    ok: bool
    sql: Optional[str] = None      # (possibly LIMIT-injected) cleaned SQL
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

    @property
    def error_message(self) -> str:
        return "; ".join(self.errors) if self.errors else ""


# ---------------------------------------------------------------------------
# Main validator
# ---------------------------------------------------------------------------

def validate_sql(raw_sql: str, max_rows: int | None = None) -> ValidationResult:
    """
    Parse and validate *raw_sql* through multiple security layers.

    Parameters
    ----------
    raw_sql : str
        The SQL string generated by the LLM (not yet executed).
    max_rows : int | None
        Maximum rows to enforce via LIMIT. Defaults to settings.max_result_rows.

    Returns
    -------
    ValidationResult
        ``ok=True`` and a cleaned ``sql`` string on success.
        ``ok=False`` with descriptive ``errors`` on failure.
    """
    if max_rows is None:
        max_rows = settings.max_result_rows

    if not raw_sql or not raw_sql.strip():
        return ValidationResult(ok=False, errors=["SQL is empty."])

    # ── Layer 1: Parse ──────────────────────────────────────────────────────
    try:
        statements = sqlglot.parse(raw_sql, dialect="postgres")
    except sqlglot.errors.ParseError as exc:
        return ValidationResult(ok=False, errors=[f"SQL parse error: {exc}"])

    if not statements or all(s is None for s in statements):
        return ValidationResult(ok=False, errors=["SQL parse produced no valid statements."])

    # Remove None entries (trailing semicolons produce None)
    statements = [s for s in statements if s is not None]

    # ── Layer 2: Exactly one statement ─────────────────────────────────────
    if len(statements) != 1:
        return ValidationResult(
            ok=False,
            errors=[
                f"Exactly one SQL statement is allowed; {len(statements)} detected. "
                "Multiple statements and statement chaining are forbidden."
            ],
        )

    stmt = statements[0]

    # ── Layer 3: Top-level must be SELECT (or CTE that produces SELECT) ────
    errors: list[str] = []
    warnings: list[str] = []

    if not isinstance(stmt, (exp.Select, exp.With)):
        errors.append(
            f"Only SELECT statements are allowed. "
            f"Detected: {type(stmt).__name__}."
        )
        return ValidationResult(ok=False, errors=errors)

    # Unwrap CTE to get the final SELECT
    if isinstance(stmt, exp.With):
        final_select = stmt.args.get("expression")
        if not isinstance(final_select, exp.Select):
            errors.append(
                "CTE (WITH clause) must end with a SELECT statement, not a DML statement."
            )
            return ValidationResult(ok=False, errors=errors)

    # ── Layer 4: No disallowed statement types anywhere in the AST ─────────
    for node in stmt.walk():
        if isinstance(node, _DISALLOWED_NODE_TYPES):
            errors.append(
                f"Disallowed SQL operation detected: {type(node).__name__}. "
                "Only SELECT is permitted."
            )

    if errors:
        return ValidationResult(ok=False, errors=errors)

    # ── Layer 5: Table allowlist & forbidden schema checks ─────────────────
    cte_aliases: set[str] = set()
    for cte in stmt.find_all(exp.CTE):
        alias = cte.alias_or_name
        if alias:
            cte_aliases.add(alias.lower())

    for table_node in stmt.find_all(exp.Table):
        table_name: str = (table_node.name or "").lower()
        schema_name: str = (
            table_node.args.get("db") or table_node.args.get("catalog") or ""
        )
        if hasattr(schema_name, "name"):
            schema_name = schema_name.name
        schema_name = (schema_name or "").lower()

        # Skip subquery aliases or CTE aliases
        if not table_name or table_name in cte_aliases:
            continue

        # Reject forbidden schemas
        if schema_name and schema_name in FORBIDDEN_SCHEMAS:
            errors.append(
                f"Access to schema '{schema_name}' is forbidden. "
                "Only the 'road_insight' schema is permitted."
            )
            continue

        # Reject staging tables by name prefix (even without schema qualifier)
        for pattern in FORBIDDEN_TABLE_PATTERNS:
            if table_name.startswith(pattern):
                errors.append(
                    f"Access to staging table '{table_name}' is forbidden. "
                    "Staging tables are excluded from the analytical context."
                )
                break
        else:
            # Enforce schema qualification OR implicitly check name in allowlist
            if schema_name and schema_name != ALLOWED_SCHEMA:
                errors.append(
                    f"Table '{schema_name}.{table_name}' references a disallowed "
                    f"schema '{schema_name}'. Only 'road_insight' is permitted."
                )
            elif table_name not in ALLOWED_TABLES:
                errors.append(
                    f"Table '{table_name}' is not in the approved analytical table "
                    "allowlist. Verify the table name."
                )

    if errors:
        return ValidationResult(ok=False, errors=errors)

    # ── Layer 6: Dangerous function calls ──────────────────────────────────
    for func_node in stmt.find_all(exp.Anonymous, exp.Func):
        func_name = ""
        if isinstance(func_node, exp.Anonymous):
            func_name = (func_node.this or "").lower()
        elif hasattr(func_node, "sql_name"):
            func_name = func_node.sql_name().lower()

        if func_name in _DANGEROUS_FUNCTIONS:
            errors.append(
                f"Dangerous function '{func_name}' is not permitted in "
                "analytical queries."
            )

    if errors:
        return ValidationResult(ok=False, errors=errors)

    # ── Layer 7: Data-modifying CTEs ───────────────────────────────────────
    for cte_node in stmt.find_all(exp.CTE):
        for dml_type in (exp.Insert, exp.Update, exp.Delete):
            if cte_node.find(dml_type):
                errors.append(
                    "Data-modifying CTEs (INSERT/UPDATE/DELETE inside WITH) "
                    "are forbidden."
                )

    if errors:
        return ValidationResult(ok=False, errors=errors)

    # ── Layer 8: Subquery recursion (apply same table rules) ───────────────
    for sub_node in stmt.find_all(exp.Subquery):
        sub_errors = _validate_subquery_tables(sub_node)
        errors.extend(sub_errors)

    if errors:
        return ValidationResult(ok=False, errors=errors)

    # ── Layer 9: LIMIT enforcement ─────────────────────────────────────────
    has_limit = _has_any_limit(stmt)

    # Find the final/outermost SELECT (the one whose results the user sees)
    outer_select = stmt if isinstance(stmt, exp.Select) else stmt.args.get("expression")

    # Check if the outer select is an aggregation query (no GROUP BY grouping → single row)
    is_pure_aggregate = _is_pure_aggregate(outer_select)

    if not has_limit and not is_pure_aggregate:
        stmt = stmt.limit(max_rows)
        warnings.append(
            f"No LIMIT clause found. LIMIT {max_rows} has been automatically added."
        )

    # ── Serialise back to clean SQL ────────────────────────────────────────
    try:
        clean_sql = stmt.sql(dialect="postgres", pretty=True)
    except Exception as exc:  # noqa: BLE001
        return ValidationResult(
            ok=False,
            errors=[f"Failed to serialise validated SQL: {exc}"],
        )

    logger.debug("SQL validation passed. Warnings: %s", warnings)
    return ValidationResult(ok=True, sql=clean_sql, warnings=warnings)


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _validate_subquery_tables(subquery_node: exp.Subquery) -> list[str]:
    """Check tables inside a subquery against the allowlist."""
    sub_errors: list[str] = []
    for table_node in subquery_node.find_all(exp.Table):
        table_name = (table_node.name or "").lower()
        schema_name = table_node.args.get("db") or table_node.args.get("catalog") or ""
        if hasattr(schema_name, "name"):
            schema_name = schema_name.name
        schema_name = (schema_name or "").lower()

        if not table_name:
            continue

        if schema_name and schema_name in FORBIDDEN_SCHEMAS:
            sub_errors.append(
                f"Subquery accesses forbidden schema '{schema_name}'."
            )
        for pattern in FORBIDDEN_TABLE_PATTERNS:
            if table_name.startswith(pattern):
                sub_errors.append(
                    f"Subquery references staging table '{table_name}' (forbidden)."
                )
                break
        else:
            if schema_name and schema_name != ALLOWED_SCHEMA:
                sub_errors.append(
                    f"Subquery references disallowed schema '{schema_name}'."
                )
            elif table_name and table_name not in ALLOWED_TABLES:
                sub_errors.append(
                    f"Subquery references unknown table '{table_name}'."
                )
    return sub_errors


def _has_any_limit(stmt: exp.Expression) -> bool:
    """Return True if the statement (or any CTE branch) already has a LIMIT."""
    return stmt.find(exp.Limit) is not None


def _is_pure_aggregate(select_node: exp.Select | None) -> bool:
    """
    Heuristic: if the outermost SELECT has aggregate functions but no GROUP BY,
    it returns a single row (e.g. SELECT SUM(...), COUNT(*) FROM ...).
    We don't need LIMIT in that case.
    """
    if select_node is None:
        return False
    has_group = select_node.args.get("group") is not None
    if has_group:
        return False  # Has GROUP BY → multiple rows possible
    # Check for top-level aggregate functions in the select list
    agg_types = (exp.Sum, exp.Count, exp.Avg, exp.Max, exp.Min, exp.Stddev)
    for sel_expr in select_node.selects:
        if any(isinstance(node, agg_types) for node in sel_expr.walk()):
            return True
    return False

